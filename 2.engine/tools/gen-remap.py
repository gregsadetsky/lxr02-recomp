#!/usr/bin/env python3
"""generate shim/lxr_remap.h + platform/lxr_remap.c from ST's device header.

every peripheral instance macro of the form
    #define NAME ((TYPE *) NAME_BASE)
is redefined to point at a plain c object, so firmware register accesses
(GPIOE->BSRR = ..., USART3->RDR, TIM2->CNT) land in memory the platform layer
can read and write, on any target. types and bit constants stay ST's own.
core peripherals (SCB, DWT, ...) are not in this header; see lxr_core_wasm.h.
usage: gen-remap.py <stm32f765xx.h> <out .h> <out .c>"""
import re, sys
src, out_h, out_c = sys.argv[1:4]
pat = re.compile(r"^#define\s+(\w+)\s+\(\(\s*(\w+)\s*\*\s*\)\s*(\w+)\s*\)\s*$")
defs = []
for line in open(src, encoding="latin-1"):
    m = pat.match(line.strip())
    if m and m.group(3).endswith("BASE"):
        defs.append((m.group(1), m.group(2)))
# several instances can share one base address (aliases); keep them distinct objects
# only if their base macros differ. collect base per name from the header too.
base_of = {}
pat_line = re.compile(r"^#define\s+(\w+)\s+\(\(\s*\w+\s*\*\s*\)\s*(\w+)\s*\)")
for line in open(src, encoding="latin-1"):
    m = pat_line.match(line.strip())
    if m: base_of[m.group(1)] = m.group(2)
with open(out_h, "w") as h:
    h.write("/* generated by tools/gen-remap.py from %s. do not edit. */\n" % src.split("/")[-1])
    h.write("#ifndef LXR_REMAP_H\n#define LXR_REMAP_H\n")
    h.write("GPIO_TypeDef *lxr_gpio_access(GPIO_TypeDef *port);\n")
    for name, typ in defs:
        b = base_of[name]
        h.write("extern %s lxr_periph_%s;\n#undef %s\n" % (typ, b, name))
        if typ == "GPIO_TypeDef":
            # gpio ports go through a call before every access, so a pending write
            # to the write-only BSRR register is applied to ODR before the next
            # access, as the real port applies it at once (lcd.c and DIO.c rely on it).
            h.write("#define %s (lxr_gpio_access(&lxr_periph_%s))\n" % (name, b))
        else:
            h.write("#define %s (&lxr_periph_%s)\n" % (name, b))
    h.write("#endif\n")
seen = set()
with open(out_c, "w") as c:
    c.write("/* generated by tools/gen-remap.py. one zero-initialised object per peripheral base. */\n")
    c.write('#include "stm32f7xx.h"\n')
    for name, typ in defs:
        b = base_of[name]
        if b in seen: continue
        seen.add(b)
        c.write("%s lxr_periph_%s;\n" % (typ, b))
print(len(defs), "instances,", len(seen), "distinct peripheral objects")
