#!/usr/bin/env python3
"""generate the wasm-only cmsis core headers in shim-wasm/ from arm's originals.

- core_cm7.h: arm's file with the core peripheral pointers (SCB, DWT, NVIC, FPU,
  SysTick, ...) remapped to plain c objects, so its inline functions
  (SCB_EnableICache, NVIC_SetPriority, ...) touch memory instead of 0xE000xxxx,
  which does not exist in a wasm address space.
- cmsis_compiler.h: the compiler macro block of arm's cmsis_gcc.h (__STATIC_INLINE,
  __PACKED, __ALIGNED, ...) verbatim, then the portable c intrinsics header
  (lxr_intrinsics.h) instead of the inline-asm ones.
the arm reference build does not use these: it compiles against arm's originals.
usage: gen-core-wasm.py <CMSIS/Include dir> <out dir>"""
import re, sys, os
inc, out = sys.argv[1:3]
os.makedirs(out, exist_ok=True)
core = open(os.path.join(inc, "core_cm7.h"), encoding="latin-1").read()
pat = re.compile(r"^(\s*)#define\s+(\w+)\s+\(\(\s*(\w+)\s*\*\s*\)\s*(\w+)\s*\)(.*)$", re.M)
externs = []
def repl(m):
    ind, name, typ, base, rest = m.groups()
    if not base.endswith("_BASE"): return m.group(0)
    externs.append((typ, name))
    return "%s#define %s (&lxr_core_%s)%s" % (ind, name, name, rest)
core2, n = pat.subn(repl, core)
decl = "".join("extern %s lxr_core_%s;\n" % (t, nm) for t, nm in externs)
# the externs must come after the type definitions and before the macros: put them
# right before the first remapped macro
first = core2.index("(&lxr_core_SCnSCB)")
line_start = core2.rfind("\n", 0, first) + 1
core2 = core2[:line_start] + "/* lxr: core peripherals remapped to memory (gen-core-wasm.py) */\n" + decl + core2[line_start:]
open(os.path.join(out, "core_cm7.h"), "w").write("/* generated from arm core_cm7.h by tools/gen-core-wasm.py. do not edit. */\n" + core2)
gcc = open(os.path.join(inc, "cmsis_gcc.h"), encoding="latin-1").read()
a = gcc.index("#ifndef   __ASM"); b = gcc.index("/* ###########################  Core Function Access")
open(os.path.join(out, "cmsis_compiler.h"), "w").write(
    "/* generated by tools/gen-core-wasm.py: macro block of arm cmsis_gcc.h + portable intrinsics. */\n"
    "#ifndef __CMSIS_COMPILER_H\n#define __CMSIS_COMPILER_H\n#include <stdint.h>\n"
    + gcc[a:b] + '\n#include "lxr_intrinsics.h"\n#endif\n')
with open(os.path.join(out, "lxr_core_objects.c"), "w") as c:
    c.write('/* generated: storage for the remapped core peripherals (wasm only). */\n#include "stm32f7xx.h"\n')
    seen = set()
    for t, nm in externs:
        if nm in seen: continue
        seen.add(nm); c.write("%s lxr_core_%s;\n" % (t, nm))
print("remapped", n and len(externs), "core peripherals:", " ".join(nm for _, nm in externs))
